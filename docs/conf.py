"""Sphinx configuration for the OrbitDet API documentation.

Docstrings are Google-style (``Args:`` / ``Returns:`` / ``Examples:``), so
``sphinx.ext.napoleon`` is required.  Equations are written as native
reStructuredText math (``.. math::`` blocks and ``:math:`` roles), which
``sphinx.ext.mathjax`` renders in the browser.

Build with ``scripts/build_docs.sh`` or directly::

    python -m sphinx -b html docs docs/_build/html
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(Path(__file__).resolve().parent / "_ext"))

project = "OrbitDet"
author = "Pascal Christiaanse"
copyright = f"2026, {author}"
release = "0.1.0"

extensions = [
    "sphinx.ext.autodoc",
    "sphinx.ext.napoleon",
    "sphinx.ext.mathjax",
    "sphinx.ext.viewcode",
    "sphinx.ext.intersphinx",
    "sphinx_copybutton",
    "sphinxcontrib.mermaid",
    "sequence_diagrams",
]

# --- autodoc ---------------------------------------------------------------
# "bysource" keeps functions in the order a reader scrolls through the file,
# which for this codebase matches the narrative in the module docstrings.
autodoc_member_order = "bysource"
autodoc_typehints = "description"
autodoc_default_options = {
    "members": True,
    "undoc-members": True,
    "show-inheritance": True,
}

# ``sphinx-apidoc`` emits a page per package *and* per submodule.  Every
# package ``__init__`` in this project only re-exports (``from .nsdb_parser
# import NSDBRecord``), so each re-exported object is rendered on both pages and
# both occurrences claim the same anchor: one "duplicate object description"
# per member.  The object genuinely appears in two places, so the warning is
# expected rather than a defect.
#
# It is deliberately not silenced.  ``:no-index:`` on the package pages removes
# the duplicates but also strips the anchors from the nine functions that are
# genuinely defined in ``reproducibility/logging/__init__.py``, and Sphinx emits
# this particular warning with no subtype, so ``suppress_warnings`` cannot
# filter it without also hiding real duplicates.  140 of the ~160 warnings are
# this one cause; the build is clean otherwise.
autodoc_inherit_docstrings = True

# --- napoleon (Google-style docstrings) ------------------------------------
napoleon_google_docstring = True
napoleon_numpy_docstring = False
napoleon_use_param = True
napoleon_use_rtype = True
napoleon_preprocess_types = True

# --- intersphinx -----------------------------------------------------------
intersphinx_mapping = {
    "python": ("https://docs.python.org/3", None),
    "numpy": ("https://numpy.org/doc/stable", None),
}

# --- math ------------------------------------------------------------------
# Pinned to the TeX input + CHTML output bundle; MathJax 3 is what the
# ``$$...$$`` delimiters emitted by the reST math directive expect.
mathjax_path = "https://cdn.jsdelivr.net/npm/mathjax@3/es5/tex-mml-chtml.js"

# --- build -----------------------------------------------------------------
exclude_patterns = ["_build", "Thumbs.db", ".DS_Store"]

# --- theme -----------------------------------------------------------------
# Furo is the theme behind modern Read-the-Docs sites: sidebar navigation,
# system-aware light/dark mode, and MathJax scroll containers that stop long
# derivations from blowing out the page width.
html_theme = "furo"
html_title = "OrbitDet"
html_static_path = ["_static"]

html_theme_options = {
    "sidebar_hide_name": False,
    "navigation_with_keys": True,
    "top_of_page_button": "edit",
    "source_repository": "https://github.com/PascalChristiaanse/NeptuneOD/",
    "source_branch": "main",
    "source_directory": "docs/",
}

# Copy button should ignore the leading prompt characters in doctest examples
# (``>>>`` / ``...``) so pasting an example gives runnable code.
copybutton_prompt_text = r">>> |\.\.\. "
copybutton_prompt_is_regexp = True

# --- mermaid (sequence diagrams) -------------------------------------------
# ``docs/diagrams/*.mmd`` are generated by ``scripts/gen_sequence_diagrams.py``
# from live traces of selected entrypoints.  The ``sequence_diagrams`` extension
# (docs/_ext/) injects each one into the docstring of the object named in
# ``docs/diagrams.yaml``, so it renders on the module's API page.  The diagrams
# render client-side with mermaid.js; the theme is set to ``neutral`` so they
# stay legible in both Furo light and dark mode.
mermaid_theme = {"theme": "neutral"}

# Default nitpicky mode reports every unresolvable cross-reference, which for a
# package this size buries the real errors.  Turn it on deliberately instead.
nitpicky = False
